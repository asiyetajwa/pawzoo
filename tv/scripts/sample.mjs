// Bakes the sample day into the app, so the APK works with no server: copies the clips and
// snapshots into assets/sample and writes src/sample.ts from a running Pawzoo server.
// Run from tv/: node scripts/sample.mjs   (the server must be running on PAWZOO_URL, default 127.0.0.1:8787)
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tv = join(here, '..');
const media = join(tv, '..', 'media');
const BASE = process.env.PAWZOO_URL ?? 'http://127.0.0.1:8787';
const post = (path, body) => fetch(BASE + path, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body ?? {}) });

// The full day (7 PM), then the escape for its alert text, then put the server back.
await post('/api/demo/reset');
await post('/api/demo/time', { time: '19:00' });
const day = await (await fetch(`${BASE}/api/day`)).json();
await post('/api/demo/escape');
const after = await (await fetch(`${BASE}/api/day`)).json();
await post('/api/demo/reset');
const alert = after.summary.openAlerts.find((a) => a.kind === 'escape');
if (!alert) throw new Error('No escape alert came back from /api/day');
const escape = after.summary.moments.find((m) => m.eventId === alert.eventId);

const files = new Set([day.pet.photo, escape?.snapshot]);
for (const c of day.reel.chapters) {
  files.add(c.clip);
  files.add(c.snapshot);
}
files.delete(undefined);
files.delete('');
for (const f of files) {
  mkdirSync(join(tv, 'assets', 'sample', dirname(f)), { recursive: true });
  copyFileSync(join(media, f), join(tv, 'assets', 'sample', f));
}

const sample = {
  pet: { name: day.pet.name },
  summary: { highlights: day.summary.highlights, moments: [...day.summary.moments, ...(escape ? [escape] : [])] },
  reel: day.reel,
};
const requires = [...files].sort().map((f) => `  '${f}': require('../assets/sample/${f}'),`).join('\n');
writeFileSync(
  join(tv, 'src', 'sample.ts'),
  `// Generated by scripts/sample.mjs from the Pawzoo server. Do not edit by hand.
// The sample day ships inside the app so it works with no server.

import type { Day } from './api';

export const SAMPLE_DAY: Day = ${JSON.stringify(sample, null, 2)};

export const SAMPLE_ALERT = ${JSON.stringify({ message: alert.message, eventId: alert.eventId }, null, 2)};

export const SAMPLE_MEDIA: Record<string, number> = {
${requires}
};
`,
);
console.log(`sample: ${String(day.reel.chapters.length)} chapters, ${String(files.size)} media files`);
